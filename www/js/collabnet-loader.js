// P10-B: CollabNET loading screen (P10-C: all editions -- Demo under /collabnet/, Free, Full).
// Shinylive 0.9.1 has no loader hook (its spinner is an internal React component) and webR downloads R and the
// packages inside a Web Worker, which a page-level fetch wrapper cannot see. So the stages below are driven only by
// signals the page CAN observe honestly; byte counts are the build-time sizes (data-* on this script tag), not live.
//   1 Downloading R      -- from page start; "loaded from cache" if the Shinylive cache already holds R.bin.wasm
//   2 Starting R         -- the Shinylive app frame exists (webR is booting in its worker)
//   3 Installing packages-- the frame's document is loading the Shiny app (package installs happen here)
//   4 Starting CollabNET -- Shiny reports connected (shiny:connected / Shiny.shinyapp.isConnected()); then fade out
// P10-C6: "taking longer than usual" follows CollabnetLoaderCore.isSlow (100 s if no stage progress for 20 s, else 120 s;
// constants in js/collabnet-loader-core.js). "While you wait" rotates the tips of THIS edition only
// (collabnet-loader-tips.js, generated by buildWASM.R from www/loader-tips/<module>.json files the edition ships).
// Preview without waiting: ?cn_loader_preview=slow. CSP-safe: external file, classes only, no inline code.
(function () {
  "use strict";
  var me = document.currentScript, d = (me && me.dataset) || {};
  var MB = function (b) { return Math.round(Number(b || 0) / 1048576); };
  var t0 = Date.now(), stage = 0, stageAt = Date.now(), done = false, el = {}, cached = false;
  var STAGES = ["Downloading R", "Starting R", "Installing packages", "Starting CollabNET"];
  var Core = window.CollabnetLoaderCore, TIPS = window.CN_LOADER_TIPS || [];
  var preview = /[?&]cn_loader_preview=slow\b/.test(location.search);
  function txt(tag, cls, s) { var e = document.createElement(tag); if (cls) e.className = cls; if (s) e.textContent = s; return e; }
  function build() {
    var box = txt("div", "cn-ld"); box.id = "cn-loader"; box.setAttribute("role", "status"); box.setAttribute("aria-live", "polite");
    var card = txt("div", "cn-ld-card"); box.appendChild(card);
    card.appendChild(txt("h1", "cn-ld-title", "Starting CollabNET"));
    var ol = txt("ol", "cn-ld-stages"); el.items = STAGES.map(function (s) { var li = txt("li", "", s); ol.appendChild(li); return li; });
    card.appendChild(ol);
    var bar = txt("div", "cn-ld-bar"); el.fill = txt("div", "cn-ld-fill"); bar.appendChild(el.fill); card.appendChild(bar);
    el.detail = txt("p", "cn-ld-detail"); card.appendChild(el.detail);
    el.time = txt("p", "cn-ld-time"); card.appendChild(el.time);
    el.stall = txt("div", "cn-ld-stall"); el.stall.hidden = true; el.stall.setAttribute("role", "alert");
    el.stall.appendChild(txt("p", "cn-ld-stall-title", "This is taking longer than usual."));
    var ul = txt("ul", "cn-ld-stall-list");
    ul.appendChild(txt("li", "", "Check your internet connection; the first visit downloads R and its packages."));
    ul.appendChild(txt("li", "", "Later visits are much faster: the files stay in your browser cache."));
    el.stall.appendChild(ul);
    // P10-C25r4: informational only -- no Reload button / "Back to collabnet.in" link here (a slow boot is still
    // progressing; reloading restarts the download). Recovery actions stay on genuine failure dialogs
    // (collabnet-session-guard.js "R session ended" overlay).
    card.appendChild(el.stall);
    if (TIPS.length && Core) buildTips(card);
    document.body.appendChild(box); el.box = box;
    render();
  }
  function buildTips(card) {
    var about = txt("section", "cn-ld-about"); about.setAttribute("aria-label", "While you wait");
    about.appendChild(txt("h2", "", "While you wait"));
    var area = txt("div", "cn-ld-tip"); area.tabIndex = 0; area.setAttribute("aria-roledescription", "tip carousel");
    var tip = txt("p", "cn-ld-tip-text"); tip.setAttribute("aria-live", "off"); area.appendChild(tip);
    var nav = txt("div", "cn-ld-tip-nav");
    var pb = txt("button", "cn-ld-tip-btn", "\u2039"); pb.type = "button"; pb.setAttribute("aria-label", "Previous tip");
    var pos = txt("span", "cn-ld-tip-pos");
    var nb = txt("button", "cn-ld-tip-btn", "\u203a"); nb.type = "button"; nb.setAttribute("aria-label", "Next tip");
    nav.appendChild(pb); nav.appendChild(pos); nav.appendChild(nb);
    about.appendChild(area); about.appendChild(nav); card.appendChild(about);
    var rot = Core.createRotator({ n: TIPS.length, onChange: function (i, how) {
      // announce only what the user asked for; automatic changes are silent (no screen-reader spam)
      tip.setAttribute("aria-live", how === "manual" ? "polite" : "off");
      tip.textContent = TIPS[i]; pos.textContent = Core.position(i, TIPS.length);
    } });
    pb.addEventListener("click", rot.prev); nb.addEventListener("click", rot.next);
    area.addEventListener("keydown", function (e) { if (e.key === "ArrowLeft") { e.preventDefault(); rot.prev(); } else if (e.key === "ArrowRight") { e.preventDefault(); rot.next(); } });
    about.addEventListener("mouseenter", function () { rot.hold("hover", true); });
    about.addEventListener("mouseleave", function () { rot.hold("hover", false); });
    about.addEventListener("focusin", function () { rot.hold("focus", true); });
    about.addEventListener("focusout", function (e) { if (!about.contains(e.relatedTarget)) rot.hold("focus", false); });
    var wheelAt = 0;
    area.addEventListener("wheel", function (e) { var t = Date.now(); if (t - wheelAt < 600 || !e.deltaY) return; wheelAt = t; e.preventDefault(); if (e.deltaY > 0) rot.next(); else rot.prev(); }, { passive: false });
    var tx = null;
    area.addEventListener("touchstart", function (e) { tx = e.touches[0].clientX; }, { passive: true });
    area.addEventListener("touchend", function (e) { if (tx === null) return; var dx = e.changedTouches[0].clientX - tx; tx = null; if (Math.abs(dx) > 40) { if (dx < 0) rot.next(); else rot.prev(); } }, { passive: true });
    el.rot = rot; rot.start();
  }
  function render() {
    if (!el.box) return;
    el.items.forEach(function (li, i) { li.className = i < stage ? "done" : i === stage ? "active" : ""; if (i === stage) li.setAttribute("aria-current", "step"); else li.removeAttribute("aria-current"); });
    el.fill.style.width = Math.round(((stage + 0.5) / STAGES.length) * 100) + "%";
    var tot = MB(Number(d.runtimeBytes || 0) + Number(d.packagesBytes || 0) + Number(d.appBytes || 0));
    el.detail.textContent = stage === 0
      ? (cached ? "Loaded from your browser cache." : "First visit: up to " + tot + " MB (R runtime " + MB(d.runtimeBytes) + " MB, " + (d.packages || "?") + " R packages " + MB(d.packagesBytes) + " MB, app " + MB(d.appBytes) + " MB). Later visits use the cache.")
      : stage === 1 ? "R (webR) is starting in your browser."
      : stage === 2 ? "Loading the R packages the app needs (" + (d.packages || "?") + " available in this build)."
      : "Starting the CollabNET app.";
  }
  function go(n) { if (n > stage && !done) { stage = n; stageAt = Date.now(); render(); } }
  function finish() { if (done) return; done = true; stage = STAGES.length; render(); if (el.rot) el.rot.stop();
    if (el.box) { el.box.classList.add("cn-ld-out"); setTimeout(function () { el.box && el.box.remove(); }, 400); } }
  function frameDoc() { var f = document.querySelector("#root iframe"); try { return f && f.contentWindow && f.contentDocument ? f : null; } catch (e) { return null; } }
  function tick() {
    if (done) return;
    var s = Math.round((Date.now() - t0) / 1000);
    if (el.time) el.time.textContent = "Elapsed: " + s + " s";
    var f = frameDoc();
    if (f) { go(1); var w = f.contentWindow;
      if (w.document && w.document.readyState !== "uninitialized" && w.document.body) go(2);
      if (w.Shiny && w.Shiny.shinyapp) { go(3); if (typeof w.Shiny.shinyapp.isConnected === "function" && w.Shiny.shinyapp.isConnected()) setTimeout(finish, 300); }
      if (w.jQuery && !f.__cnHooked) { f.__cnHooked = true; w.jQuery(w.document).on("shiny:connected", function () { go(3); setTimeout(finish, 300); }); }
    }
    if (el.stall && el.stall.hidden && (preview || (Core ? Core.isSlow(Date.now(), t0, stageAt) : Date.now() - t0 > 120000))) el.stall.hidden = false;
    setTimeout(tick, 250);
  }
  function checkCache() {
    if (!("caches" in window)) return;
    var url = new URL("shinylive/webr/R.bin.wasm", location.href).href;
    caches.match(url).then(function (r) { if (r) { cached = true; render(); } }).catch(function () {});
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", function () { build(); checkCache(); tick(); });
  else { build(); checkCache(); tick(); }
})();
